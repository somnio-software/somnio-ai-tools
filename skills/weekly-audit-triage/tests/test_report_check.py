def config(window=14, audits=None):
    """Closebook's config as repo_config.py prints it: D8's audits with their defaults applied."""
    if audits is None:
        audits = [
            {"skill": "security-audit", "path": "."},
            {"skill": "nestjs-health-audit", "path": "apps/api"},
            {"skill": "react-health-audit", "path": "apps/web"},
            {"skill": "dora-metrics", "path": "."},
        ]
    return {
        "repo": REPO,
        "report_name": KEY,
        "audits": [{"report_name": KEY, **audit} for audit in audits],
        "dora": {"window_days": window, "prod_branch": "develop"},
    }


class ReportTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def write(self, name, text="# Report\n\nA finding.\n"):
        path = os.path.join(self.tmp.name, name)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        return path

    def reasons(self, name, text="# Report\n\nA finding.\n", cfg=None):
        return report_check.check(self.write(name, text), cfg or config(), DATE)


class TestNames(ReportTest):
    def test_each_configured_audit_passes(self):
        for typ in ("security-audit", "nestjs-health-audit", "react-health-audit"):
            with self.subTest(typ=typ):
                self.assertEqual(self.reasons(f"{DATE}-{KEY}-{typ}.md"), [])
        self.assertEqual(self.reasons(f"{DATE}-{KEY}-dora-metrics.md", dora_report()), [])

    def test_without_audits_every_accepted_type_passes(self):
        cfg = {"repo": REPO, "report_name": KEY, "dora": {"window_days": 14}}
        for typ in report_check.ACCEPTED_TYPES:
            with self.subTest(typ=typ):
                text = dora_report() if typ == "dora-metrics" else "# Report\n"
                self.assertEqual(self.reasons(f"{DATE}-{KEY}-{typ}.md", text, cfg), [])

    def test_types_the_spreadsheet_rejects(self):
        for typ in ("nextjs-health-audit", "nextjs-security-audit", "harness-audit", "weekly-summary",
                    "nestjs-health-audit-api"):
            with self.subTest(typ=typ):
                reasons = self.reasons(f"{DATE}-{KEY}-{typ}.md")
                self.assertEqual(len(reasons), 1, reasons)
                self.assertIn(f"type '{typ}' is not one the spreadsheet reads", reasons[0])

    def test_an_accepted_type_no_audit_writes(self):
        self.assertEqual(self.reasons(f"{DATE}-{KEY}-python-health-audit.md"),
                         [f"no audit in the config writes 'python-health-audit' under '{KEY}'"])

    def test_a_key_other_than_the_configs(self):
        self.assertEqual(self.reasons(f"{DATE}-somnio-finance-platform-security-audit.md"),
                         [f"the repository key is not '{KEY}'"])

    def test_another_date(self):
        self.assertEqual(self.reasons(f"2026-11-16-{KEY}-security-audit.md"),
                         [f"dated 2026-11-16, not the run date {DATE}"])

    def test_no_date(self):
        self.assertEqual(self.reasons(f"{KEY}-security-audit.md"),
                         ["the name does not start with a YYYY-MM-DD date"])

    def test_a_file_that_is_not_markdown(self):
        self.assertEqual(self.reasons(f"{DATE}-{KEY}-security-audit.json"), ["not a .md file"])
        self.assertIn("not a .md file", self.reasons("findings.json", "[]"))

    def test_an_empty_file(self):
        self.assertEqual(self.reasons(f"{DATE}-{KEY}-security-audit.md", ""), ["the file is empty"])
        self.assertEqual(self.reasons(f"{DATE}-{KEY}-dora-metrics.md", " \n"), ["the file is empty"])

    def test_an_unreadable_file(self):
        reasons = report_check.check(os.path.join(self.tmp.name, f"{DATE}-{KEY}-security-audit.md"),
                                     config(), DATE)
        self.assertEqual(len(reasons), 1)
        self.assertTrue(reasons[0].startswith("cannot read it:"), reasons)

    def test_an_audit_without_its_default_key_uses_the_configs(self):
        cfg = {"repo": REPO, "report_name": KEY, "audits": [{"skill": "security-audit"}]}
        self.assertEqual(self.reasons(f"{DATE}-{KEY}-security-audit.md", cfg=cfg), [])

    def test_an_audits_own_key(self):
        cfg = config(audits=[{"skill": "security-audit", "path": "."},
                             {"skill": "react-health-audit", "path": "apps/web", "report_name": f"{KEY}-web"}])
        self.assertEqual(self.reasons(f"{DATE}-{KEY}-web-react-health-audit.md", cfg=cfg), [])
        self.assertEqual(self.reasons(f"{DATE}-{KEY}-react-health-audit.md", cfg=cfg),
                         [f"no audit in the config writes 'react-health-audit' under '{KEY}'"])


class TestDora(ReportTest):
    NAME = f"{DATE}-{KEY}-dora-metrics.md"

    def test_the_new_heading_and_window_pass(self):
        self.assertEqual(self.reasons(self.NAME, dora_report(14)), [])

    def test_the_2026_11_23_heading_fails(self):
        reasons = self.reasons(self.NAME, DORA_2026_11_23, config(window=7))
        self.assertEqual(reasons, [
            f"no line is exactly '## {REPO}'",
            f"heading '## `{REPO}` (web, backend) — deploy_source: merge' is not exactly '## {REPO}'",
        ])

    def test_a_14_day_report_fails_against_a_7_day_config(self):
        self.assertEqual(self.reasons(self.NAME, dora_report(14), config(window=7)),
                         ["the measurement window is 14 days, the config's is 7"])

    def test_a_report_without_the_window_row(self):
        text = dora_report().replace("| Measurement window | 14 days |\n", "")
        self.assertEqual(self.reasons(self.NAME, text), ["no '| Measurement window | N days |' row"])

    def test_a_config_without_dora(self):
        cfg = {"repo": REPO, "report_name": KEY}
        self.assertEqual(self.reasons(self.NAME, dora_report(), cfg),
                         ["the config has no 'dora.window_days' to check the window against"])

    def test_the_heading_is_checked_only_on_dora_reports(self):
        self.assertEqual(self.reasons(f"{DATE}-{KEY}-security-audit.md", DORA_2026_11_23), [])


class TestCommandLine(ReportTest):
    def run_script(self, *args):
        return subprocess.run([sys.executable, SCRIPT_PATH, *args], capture_output=True, text=True)

    def config_file(self, cfg=None):
        return self.write("config.json", json.dumps(cfg or config()))

    def test_every_report_passes_exits_0(self):
        good = self.write(f"{DATE}-{KEY}-security-audit.md")
        dora = self.write(f"{DATE}-{KEY}-dora-metrics.md", dora_report())
        result = self.run_script(self.config_file(), DATE, good, dora)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(result.stdout.splitlines(), [f"PASS {good}", f"PASS {dora}"])

    def test_a_failing_report_prints_one_line_per_reason_and_exits_2(self):
        good = self.write(f"{DATE}-{KEY}-security-audit.md")
        bad = self.write(f"2026-11-16-{KEY}-nextjs-health-audit.md", "")
        result = self.run_script(self.config_file(), DATE, good, bad)
        self.assertEqual(result.returncode, 2)
        self.assertEqual(result.stdout.splitlines(), [
            f"PASS {good}",
            f"FAIL {bad}: the file is empty",
            f"FAIL {bad}: dated 2026-11-16, not the run date {DATE}",
            f"FAIL {bad}: type 'nextjs-health-audit' is not one the spreadsheet reads ("
            + ", ".join(report_check.ACCEPTED_TYPES) + ")",
        ])

    def test_usage_errors_exit_2(self):
        for args in ((), (self.config_file(), DATE), (self.config_file(), "23/11/2026", "x.md")):
            with self.subTest(args=args):
                result = self.run_script(*args)
                self.assertEqual(result.returncode, 2)
                self.assertIn("Usage", result.stderr)

    def test_an_unreadable_config_exits_2(self):
        result = self.run_script(self.write("config.json", "{not json"), DATE, "x.md")
        self.assertEqual(result.returncode, 2)
        self.assertIn("cannot read the config", result.stderr)

    def test_a_raw_config_exits_2(self):
        result = self.run_script(self.config_file({"repo": REPO}), DATE, "x.md")
        self.assertEqual(result.returncode, 2)
        self.assertIn("repo_config.py's output", result.stderr)


# The `## ` headings of a security-audit report as its template writes them (skills/security-audit), with
# the five scored sections ordered by score, as the 2026-11-16 run did.
SECURITY_SECTIONS = [
    "1. Security Scoring Breakdown",
    "2. Executive Summary",
    "3. Secret Detection",
    "4. Sensitive File Protection",
    "5. Dependency Security",
    "6. Supply Chain Integrity",
    "7. Security Automation & CI/CD",
    "8. Consolidated Findings by Severity",
    "9. Remediation Priority Matrix",
    "10. Project Detection Results",
    "11. Appendix: Evidence Index",
    "Appendix: Scoring Methodology",
    "12. Report Metadata",
]
PREVIOUS_DATE = "2026-11-16"
REPO_SHA = "698e2950" + "a" * 32
AI_REF = "e160a38" + "b" * 33


def report(headings, notes=(), title="# Security Audit Report — closebook-finance-platform"):
    """A report with a title, its run notes right under it (D6) and one paragraph per `## ` heading."""
    body = "".join(f"\n## {heading}\n\nText of {heading}.\n" for heading in headings)
    return "\n".join([title, *notes]) + "\n" + body


def run_line(repo_sha=REPO_SHA, ref=AI_REF):
    return f"> Run: {REPO} @ {repo_sha} · somnio-ai-tools @ {ref}"


class PreviousTest(ReportTest):
    NAME = f"{DATE}-{KEY}-security-audit.md"

    def setUp(self):
        super().setUp()
        self.previous = os.path.join(self.tmp.name, "previous")
        os.mkdir(self.previous)

    def write_previous(self, name, text):
        with open(os.path.join(self.previous, name), "w", encoding="utf-8") as fh:
            fh.write(text)

    def lines(self, text, name=None):
        return report_check.section_lines(self.write(name or self.NAME, text), config(), DATE, self.previous)


class TestSections(PreviousTest):
    def setUp(self):
        super().setUp()
        self.write_previous(f"{PREVIOUS_DATE}-{KEY}-security-audit.md", report(SECURITY_SECTIONS))

    def test_a_missing_section_fails_and_prints_the_note_to_add(self):
        path = os.path.join(self.tmp.name, self.NAME)
        current = [h for h in SECURITY_SECTIONS if h != "6. Supply Chain Integrity"]
        self.assertEqual(self.lines(report(current)), [
            f"FAIL {path}: sections missing since {PREVIOUS_DATE} not noted",
            f"> ⚠️ Sections missing since {PREVIOUS_DATE}: Supply Chain Integrity",
        ])

    def test_the_noted_report_gives_a_warning(self):
        path = os.path.join(self.tmp.name, self.NAME)
        current = [h for h in SECURITY_SECTIONS if h not in ("2. Executive Summary", "6. Supply Chain Integrity")]
        note = f"> ⚠️ Sections missing since {PREVIOUS_DATE}: Executive Summary; Supply Chain Integrity"
        self.assertEqual(self.lines(report(current, [run_line(), note])), [
            f"WARN {path}: sections missing since {PREVIOUS_DATE}: Executive Summary; Supply Chain Integrity"])

    def test_a_note_for_other_sections_still_fails(self):
        current = [h for h in SECURITY_SECTIONS if h != "6. Supply Chain Integrity"]
        note = f"> ⚠️ Sections missing since {PREVIOUS_DATE}: Secret Detection"
        self.assertTrue(self.lines(report(current, [note]))[0].startswith("FAIL "))

    def test_renumbered_reordered_and_new_sections_give_nothing(self):
        scored = ["Supply Chain Integrity", "Secret Detection", "Dependency Security",
                  "Security Automation & CI/CD", "Sensitive File Protection"]
        current = (SECURITY_SECTIONS[:2] + [f"{i}. {name}" for i, name in enumerate(scored, 3)]
                   + ["8. Infrastructure"] + [f"{i}. {h.split('. ', 1)[1]}" for i, h in
                                               enumerate(SECURITY_SECTIONS[7:11], 9)]
                   + SECURITY_SECTIONS[11:])
        self.assertEqual(self.lines(report(current)), [])

    def test_a_report_without_sections_misses_every_one(self):
        lines = self.lines("# Security Audit Report\n\nNothing.\n")
        self.assertEqual(len(lines), 2)
        self.assertTrue(lines[1].endswith(": Security Scoring Breakdown; Executive Summary; Secret Detection; "
                                          "Sensitive File Protection; Dependency Security; Supply Chain Integrity;"
                                          " Security Automation & CI/CD; Consolidated Findings by Severity; "
                                          "Remediation Priority Matrix; Project Detection Results; Appendix: "
                                          "Evidence Index; Appendix: Scoring Methodology; Report Metadata"), lines)

    def test_headings_inside_code_fences_are_not_sections(self):
        self.write_previous(f"{PREVIOUS_DATE}-{KEY}-security-audit.md",
                            report(SECURITY_SECTIONS) + "\n```markdown\n## Example heading\n```\n")
        self.assertEqual(self.lines(report(SECURITY_SECTIONS)), [])


class TestPreviousSelection(PreviousTest):
    def test_the_newest_earlier_report_of_the_same_key_and_type_is_used(self):
        self.write_previous(f"2026-11-09-{KEY}-security-audit.md", report(SECURITY_SECTIONS + ["Older"]))
        self.write_previous(f"{PREVIOUS_DATE}-{KEY}-security-audit.md", report(SECURITY_SECTIONS))
        self.write_previous(f"{DATE}-{KEY}-security-audit.md", report(SECURITY_SECTIONS + ["Same day"]))
        self.write_previous(f"2026-11-30-{KEY}-security-audit.md", report(SECURITY_SECTIONS + ["Later"]))
        self.write_previous(f"2026-11-20-{KEY}-nestjs-health-audit.md", report(["Other type"]))
        self.write_previous(f"2026-11-20-other-repo-security-audit.md", report(["Other key"]))
        self.write_previous(f"2026-11-20-{KEY}-security-audit.json", report(["Not markdown"]))
        self.assertEqual(self.lines(report(SECURITY_SECTIONS)), [])

    def test_no_previous_report_is_a_note(self):
        path = os.path.join(self.tmp.name, self.NAME)
        self.write_previous(f"2026-11-20-{KEY}-nestjs-health-audit.md", report(["Other type"]))
        self.assertEqual(self.lines(report(SECURITY_SECTIONS)), [f"NOTE {path}: no previous report"])

    def test_an_empty_previous_report_counts_as_none(self):
        path = os.path.join(self.tmp.name, self.NAME)
        self.write_previous(f"2026-11-09-{KEY}-security-audit.md", report(SECURITY_SECTIONS + ["Older"]))
        self.write_previous(f"{PREVIOUS_DATE}-{KEY}-security-audit.md", " \n")
        self.assertEqual(self.lines(report(SECURITY_SECTIONS)), [f"NOTE {path}: no previous report"])

    def test_a_report_whose_name_fails_is_not_compared(self):
        self.write_previous(f"{PREVIOUS_DATE}-{KEY}-security-audit.md", report(SECURITY_SECTIONS))
        self.assertEqual(self.lines("# x\n", name=f"{DATE}-{KEY}-nextjs-health-audit.md"), [])


